// 逆引きマップ(en小文字/ko → 日本語正規名)。初回アクセス時に構築
let _reverse = null;
function reverse() {
  if (_reverse) return _reverse;
  _reverse = {};
  for (const [ja, [en, ko]] of Object.entries(CHAMP_I18N)) {
    _reverse[en.toLowerCase()] = ja;
    _reverse[ko] = ja;
  }
  return _reverse;
}

// 表示用: 日本語正規名 → 現在言語の表記(未知名・学習名はそのまま)
export function champLabel(name) {
  if (!name) return name;
  const lang = getLang();
  if (lang === "ja") return name;
  const e = CHAMP_I18N[name];
  if (!e) return name;
  return lang === "ko" ? e[1] : e[0];
}

// 保存用: 入力値(任意言語) → 日本語正規名。既知でなければ入力値をそのまま返す
export function champCanonical(input) {
  const v = (input || "").trim();
  if (!v) return v;
  if (CHAMP_I18N[v]) return v; // 既に日本語正規名
  return reverse()[v.toLowerCase()] ?? reverse()[v] ?? v;
}
