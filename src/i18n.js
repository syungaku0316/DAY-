let currentLang = "ja";
export function setLang(l) { currentLang = l; }
export function getLang() { return currentLang; }

// フォールバック: 現在言語 -> ja -> キー名そのまま
export function t(key, vars) {
  const s = (DICT[currentLang] && DICT[currentLang][key]) ?? DICT.ja[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// ランク名の表示変換(DB保存値·プルダウンvalueは日本語のまま。表示のみ変換)
const RANK_LABEL = {
  "チャレンジャー": { ko: "챌린저", en: "Challenger" },
  "グランドマスター": { ko: "그랜드마스터", en: "Grandmaster" },
  "マスター": { ko: "마스터", en: "Master" },
  "アンランク": { ko: "언랭크", en: "Unranked" },
  "初心者": { ko: "초보자", en: "Beginner" },
};
export function rankLabel(rank) {
  if (currentLang === "ja") return rank;
  return (RANK_LABEL[rank] && RANK_LABEL[rank][currentLang]) ?? rank;
}

// RANK_SHORT の言語別短縮表記(表示専用)
const RANK_SHORT_LANG = {
  ja: { "マスター": "M", "グランドマスター": "GM", "チャレンジャー": "C", "アンランク": "U", "初心者": "初" },
  en: { "マスター": "M", "グランドマスター": "GM", "チャレンジャー": "C", "アンランク": "U", "初心者": "B" },
  ko: { "マスター": "M", "グランドマスター": "GM", "チャレンジャー": "C", "アンランク": "U", "初心者": "초" },
};
export function rankShortLang(rank) {
  const m = RANK_SHORT_LANG[currentLang] || RANK_SHORT_LANG.ja;
  return m[rank] || rank;
}

const DATE_LOCALES = { ja: "ja-JP", en: "en-US", ko: "ko-KR" };
export function dateLocale() { return DATE_LOCALES[currentLang] || "ja-JP"; }

export function initialLang() {
  try {
    const saved = localStorage.getItem("crl-lang");
    if (saved) return saved;
  } catch {}
  const nav = (typeof navigator !== "undefined" && navigator.language || "").toLowerCase();
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("en")) return "en";
  return "ja";
}
