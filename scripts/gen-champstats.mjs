// チャンピオン基礎ステータス生成スクリプト
//   実行: node scripts/gen-champstats.mjs
//   出力: src/champStats.js（Vite バンドルへ同梱。ランタイム fetch はしない）
//
// データ源:
//   - チャンピオン一覧 / 表示名 / patch: DDragon championFull.json
//   - 実ステータス: CommunityDragon の実ゲームファイル characters/<name>.bin.json
//     （DDragon は一部チャンプで attackdamageperlevel 等が 0 のまま等ズレがあるため CDragon を正とする。
//       CDragon は attackSpeedRatio も持つ。regen は内部値=毎秒なので ×5 して毎5秒表記に直す）
//
// arType: 0=マナ 1=エナジー それ以外=独自リソース（成長なし）/ 無し
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "../src/champStats.js");

const AR_TYPE = {
  0: "MANA", 1: "ENERGY", 2: "NONE", 3: "NONE", 4: "RAGE", 5: "NONE",
  6: "FURY", 7: "HEAT", 8: "GNARFURY", 9: "FEROCITY", 10: "BLOODWELL",
  11: "FLOW", 12: "AMMO", 13: "MANA", 14: "OTHER",
};

const RES_BASE = "{726ee5cd}";   // 独自リソース基礎量
const RES_PERLV = "{6216bf7b}";  // 同 成長

const num = (v) => (v && typeof v === "object" ? v.baseValue : v) ?? 0;
const r2 = (n) => Math.round(n * 1000) / 1000;

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

async function main() {
  const versions = await getJson("https://ddragon.leagueoflegends.com/api/versions.json");
  const patch = versions[0];
  console.log("patch:", patch);
  const full = await getJson(`https://ddragon.leagueoflegends.com/cdn/${patch}/data/en_US/championFull.json`);
  // 表示名は DDragon 公式ローカライズを同梱（champNames.js の辞書に依存しない＝新チャンピオンも正しく出る）
  const nameByLocale = { en: full };
  for (const [k, loc] of [["ja", "ja_JP"], ["ko", "ko_KR"]]) {
    try { nameByLocale[k] = await getJson(`https://ddragon.leagueoflegends.com/cdn/${patch}/data/${loc}/championFull.json`); }
    catch { nameByLocale[k] = full; }
  }
  const champs = Object.values(full.data); // { id, key, name, ... }
  champs.sort((a, b) => a.name.localeCompare(b.name));

  const out = {};
  const skipped = [];

  for (const c of champs) {
    const slug = c.id.toLowerCase();
    let root;
    for (const cand of [slug, slug.replace(/[^a-z0-9]/g, "")]) {
      try {
        const bin = await getJson(`https://raw.communitydragon.org/latest/game/data/characters/${cand}/${cand}.bin.json`);
        const key = Object.keys(bin).find((k) => /CharacterRecords\/Root$/.test(k));
        if (key) { root = bin[key]; break; }
      } catch { /* 次の候補へ */ }
    }
    if (!root) { skipped.push(c.id); continue; }

    const par = root.primaryAbilityResource || {};
    const resource = AR_TYPE[par.arType] || "NONE";
    const isMana = resource === "MANA";

    out[c.name] = {
      key: Number(c.key),
      nameJa: nameByLocale.ja.data[c.id]?.name || c.name,
      nameKo: nameByLocale.ko.data[c.id]?.name || c.name,
      hp: r2(num(root.baseHPModifiable)),
      hpPerLv: r2(num(root.hpPerLevelModifiable)),
      mp: isMana ? r2(num(par[RES_BASE])) : 0,
      mpPerLv: isMana ? r2(num(par[RES_PERLV])) : 0,
      ad: r2(num(root.baseDamageModifiable)),
      adPerLv: r2(num(root.damagePerLevelModifiable)),
      armor: r2(num(root.baseArmorModifiable)),
      armorPerLv: r2(num(root.armorPerLevelModifiable)),
      mr: r2(num(root.baseMR)),
      mrPerLv: r2(num(root.mrPerLevel)),
      hp5: r2(num(root.baseStaticHPRegenModifiable) * 5),
      hp5PerLv: r2(num(root.hpRegenPerLevelModifiable) * 5),
      mp5: isMana ? r2(num(par["{c4ab3550}"]) * 5) : 0,
      mp5PerLv: isMana ? r2(num(par["{3a509002}"]) * 5) : 0,
      as: r2(num(root.attackSpeedModifiable)),
      asRatio: r2(num(root.attackSpeedRatioModifiable) || num(root.attackSpeedModifiable)),
      asPerLv: r2(num(root.attackSpeedPerLevelModifiable)),
      ms: r2(num(root.baseMoveSpeedModifiable)),
      range: r2(num(root.attackRangeModifiable)),
      resource,
    };
    process.stdout.write(".");
  }
  process.stdout.write("\n");
  if (skipped.length) console.warn("CDragon 取得失敗:", skipped.join(", "));

  const body =
    "// AUTO-GENERATED by scripts/gen-champstats.mjs — 手で編集しない\n" +
    "// regen は毎5秒表記。as=基礎攻撃速度 / asRatio=ボーナスAS%係数 / asPerLv=成長%\n" +
    `export const CHAMPSTATS_PATCH = ${JSON.stringify(patch)};\n` +
    `export const CHAMPSTATS_GENERATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\n` +
    "export const CHAMPSTATS = {\n" +
    Object.entries(out)
      .map(([name, s]) => `  ${JSON.stringify(name)}: ${JSON.stringify(s)},`)
      .join("\n") +
    "\n};\n";

  fs.writeFileSync(OUT, body);
  console.log(`wrote ${OUT}  (${Object.keys(out).length} champions)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
